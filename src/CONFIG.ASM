    assert RENDER_CACHE+4*80 <= CURSOR_CACHE
    assert CURSOR_CACHE+4*80 <= CACHE_COLORS
    assert CACHE_COLORS+4 <= PAIR_TABLE
    assert PAIR_TABLE+4 <= DIRTY
    assert INPUT_OLD+INPUT_ROWS*GRID_STRIDE <= PIXEL_LUT0
    assert PIXEL_LUT2+256 <= VRAM_BACKUP

