; Keep expanded 80-column UI buffers disjoint.
    assert GRID+TEXT_ROWS*GRID_STRIDE <= EDITOR
    assert EDITOR+EDITOR_MAX+1 <= ROWBUF
    assert ROWBUF+256 <= NAMES
    assert NAMES+768 <= DIRTY
    assert DIRTY+TEXT_ROWS <= ROWCOLORS
    assert ROWCOLORS+TEXT_ROWS <= OVERLAY_BACKUP
    assert OVERLAY_BACKUP+OVERLAY_ROWS*GRID_STRIDE <= OVERLAY_COLORS
    assert OVERLAY_COLORS+OVERLAY_ROWS <= INPUT_OLD
    assert INPUT_OLD+INPUT_ROWS*GRID_STRIDE <= VRAM_BACKUP

; Render cache for status + three editor rows; former unused NAMES area.
